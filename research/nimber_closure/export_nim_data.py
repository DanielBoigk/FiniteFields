# Exports the R1 rank-encoding data (data/rank/n_*.txt) for the package: src/nim_data.jl.
# Run from the repository root: python3 research/nimber_closure/export_nim_data.py
import glob, hashlib, re

rows = {}
for f in glob.glob('research/nimber_closure/data/rank/n_*.txt'):
    n = int(re.search(r'n_(\d+)\.txt', f).group(1))
    d = {}
    for line in open(f):
        k, v = line.rstrip('\n').split('\t')
        d[k] = v
    rows[n] = d

def hexcat(vals, n):
    w = (n + 3) // 4
    return ''.join(format(int(v), '0%dx' % w) for v in vals)

src = hashlib.sha256(''.join(open(f).read() for f in sorted(glob.glob('research/nimber_closure/data/rank/n_*.txt'))).encode()).hexdigest()
out = ['''# Generated by research/nimber_closure/export_nim_data.py from the R1 data
# (research/nimber_closure/data/rank/n_*.txt, sha256 of their concatenation in name order:
# %s). Do not edit by hand.
#
# For every n ≤ 128 that is not a power of two, in rank coordinates of GF(2^n) ⊂ On_2 (ADR-0005):
#   NIM_GEN[n]  the rank of the internal generator g (the first basis element of degree n);
#   NIM_LOW[n]  its minimal polynomial x^n + Σ low_i x^i, as the bits low;
#   NIM_C[n]    rank(g^i), i = 0 … n-1, each as cld(n, 4) hex digits, concatenated;
#   NIM_EMB[(m, n)]  rank_n(b_i), i = 0 … m-1, for the rank basis b_i of GF(2^m), m | n, m < n
#               (the inclusion GF(2^m) ⊂ GF(2^n)), concatenated the same way.
''' % src]
pw = [n for n in sorted(rows) if n & (n - 1)]
out.append('const NIM_GEN = Dict{Int, UInt128}(' + ', '.join('%d => 0x%x' % (n, int(rows[n]['g'])) for n in pw) + ')')
out.append('const NIM_LOW = Dict{Int, UInt128}(' + ', '.join('%d => 0x%x' % (n, int(rows[n]['low'])) for n in pw) + ')')
out.append('const NIM_C = Dict{Int, String}(')
for n in pw:
    out.append('    %d => "%s",' % (n, hexcat(rows[n]['C'].split(','), n)))
out.append(')')
out.append('const NIM_EMB = Dict{Tuple{Int, Int}, String}(')
for n in sorted(rows):
    for k, v in rows[n].items():
        if k.startswith('embed'):
            m = int(k.split()[1])
            out.append('    (%d, %d) => "%s",' % (m, n, hexcat(v.split(','), n)))
out.append(')')
open('julia/FiniteFieldArithmetic.jl/src/nim_data.jl', 'w').write('\n'.join(out) + '\n')
print('wrote', sum(len(l) + 1 for l in out), 'bytes')
